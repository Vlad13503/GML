"""Applies the confirmation rule in STRESS_TEST_PLAN.md to Enron seeds 3-12. Run from the repo root."""
import json
from pathlib import Path

import numpy as np
from sklearn.metrics import average_precision_score

RESULTS = Path("results")
OUTPUT = Path("analysis/stress_confirm_results.md")
ARMS = ("matched_unseen", "matched_targets", "matched_all")
SEEDS = tuple(range(3, 13))
MODELS = ("deepsets", "gcn", "allset", "allset_cpa", "allset_cpa_encoder", "allset_size")
MECHANISMS = ("allset_cpa", "allset_cpa_encoder", "allset_size")
METRICS = {2: ("all", 3, 4, 5), 3: ("all", 4, 5)}
T_CRITICAL = 2.262  # Two-sided 95%, 9 degrees of freedom.


def ap(path, metric):
    data = np.load(path)
    mask = np.ones(len(data["labels"]), bool) if metric == "all" else data["sizes"] == metric
    return average_precision_score(data["labels"][mask], data["logits"][mask])


def find_suites():
    suites = {}
    for suite in RESULTS.iterdir():
        config = suite / "config.json"
        if not config.exists():
            continue
        config = json.loads(config.read_text(encoding="utf-8"))
        experiment = config["experiments"][0]
        if config["seeds"] == list(SEEDS) and experiment["protocol"] in ARMS:
            suites[(experiment["protocol"], experiment["k"])] = suite
    return suites


def run_dir(suites, arm, k, seed, model):
    return suites[(arm, k)] / "email-Enron" / f"{arm}-k{k}" / f"seed-{seed}" / model


def summary(deltas):
    deltas = np.array(deltas)
    mean, sd = deltas.mean(), deltas.std(ddof=1)
    t = mean / (sd / np.sqrt(len(deltas))) if sd else 0.
    half = T_CRITICAL * sd / np.sqrt(len(deltas))
    return mean, mean - half, mean + half, int((deltas > 0).sum()), t


def main():
    suites = find_suites()
    assert len(suites) == 6, f"Expected 6 suites, found {len(suites)}"
    lines = ["# Stress-test confirmation: Enron, seeds 3-12", "", "Generated by `analysis/stress_confirm.py`. Intervals are 95% paired t intervals over 10 seeds, not corrected for the number of comparisons.", ""]
    for k, metrics in METRICS.items():
        cache = {(arm, s, model, m): ap(run_dir(suites, arm, k, s, model) / "test_predictions.npz", m)
                 for arm in ARMS for s in SEEDS for model in MODELS for m in metrics}
        lines += [f"## k={k}: loss from never seeing large hyperedges", "",
                  "| Model | Size | Unseen AP | Targets loss [95% CI] | Seeds + | Confirmed | All loss [95% CI] | Seeds + |", "|---|---|---|---|---|---|---|---|"]
        for model in MODELS:
            for m in metrics:
                unseen = [cache[("matched_unseen", s, model, m)] for s in SEEDS]
                primary = summary([cache[("matched_targets", s, model, m)] - u for s, u in zip(SEEDS, unseen)])
                secondary = summary([cache[("matched_all", s, model, m)] - u for s, u in zip(SEEDS, unseen)])
                confirmed = primary[0] >= .02 and primary[1] > 0
                lines.append(f"| {model} | {m} | {np.mean(unseen):.3f} | {primary[0]:+.3f} [{primary[1]:+.3f}, {primary[2]:+.3f}] | {primary[3]}/10 | "
                             f"{'YES' if confirmed else 'no'} | {secondary[0]:+.3f} [{secondary[1]:+.3f}, {secondary[2]:+.3f}] | {secondary[3]}/10 |")
        lines += ["", f"## k={k}: mechanism minus AllSet", "",
                  "A mechanism gain specific to unseen sizes should appear on the unseen arm test set, but not on validation or once large hyperedges are seen.", "",
                  "| Mechanism | Size | Unseen test [95% CI] | Seeds + | Confirmed | Targets test [95% CI] | Unseen validation [95% CI] |", "|---|---|---|---|---|---|---|"]
        for mechanism in MECHANISMS:
            for m in metrics:
                test = summary([cache[("matched_unseen", s, mechanism, m)] - cache[("matched_unseen", s, "allset", m)] for s in SEEDS])
                seen = summary([cache[("matched_targets", s, mechanism, m)] - cache[("matched_targets", s, "allset", m)] for s in SEEDS])
                row = f"| {mechanism} | {m} | {test[0]:+.3f} [{test[1]:+.3f}, {test[2]:+.3f}] | {test[3]}/10 | {'YES' if test[1] > 0 else 'no'} | {seen[0]:+.3f} [{seen[1]:+.3f}, {seen[2]:+.3f}] | "
                if m == "all":
                    val = summary([ap(run_dir(suites, "matched_unseen", k, s, mechanism) / "val_predictions.npz", "all")
                                   - ap(run_dir(suites, "matched_unseen", k, s, "allset") / "val_predictions.npz", "all") for s in SEEDS])
                    row += f"{val[0]:+.3f} [{val[1]:+.3f}, {val[2]:+.3f}] |"
                else:
                    row += "- |"
                lines.append(row)
        lines.append("")
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUTPUT}")


if __name__ == "__main__":
    main()
