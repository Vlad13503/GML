"""Applies the decision rules in STRESS_TEST_PLAN.md to the matched-arm suites. Run from the repo root.

Usage: python analysis/stress_test.py [output.md]
"""
import json
import sys
from collections import defaultdict
from pathlib import Path

import numpy as np
from sklearn.metrics import average_precision_score, f1_score

RESULTS = Path("results")
OUTPUT = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("analysis/stress_test_results.md")
ARMS = ("matched_unseen", "matched_targets", "matched_all")
DATASETS = ("email-Enron", "tags-ask-ubuntu")
KS = (2, 3)
SEEDS = (0, 1, 2)
MODELS = ("deepsets", "gcn", "allset", "allset_cpa", "allset_cpa_encoder", "allset_size")
MECHANISMS = ("allset_cpa", "allset_cpa_encoder", "allset_size")
MIN_POSITIVES, MIN_LOSS = 20, .02


def best_threshold(labels, logits):
    candidates = np.unique(logits)
    if len(candidates) > 2000:
        candidates = np.quantile(logits, np.linspace(0, 1, 2001))
    scores = [f1_score(labels, logits >= t, zero_division=0) for t in candidates]
    return candidates[int(np.argmax(scores))]


def score(run):
    val, test = [np.load(run / f"{name}_predictions.npz") for name in ("val", "test")]
    y, sizes, logits = test["labels"], test["sizes"], test["logits"]
    threshold = best_threshold(val["labels"], val["logits"])
    predicted = logits >= threshold
    out = {"ap_all": average_precision_score(y, logits), "f1_all": f1_score(y, predicted, zero_division=0),
           "fpr_all": predicted[y == 0].mean()}
    for size in np.unique(sizes):
        mask = sizes == size
        if y[mask].sum() and (y[mask] == 0).sum():
            out[f"ap_{size}"] = average_precision_score(y[mask], logits[mask])
    return out, y.astype(int).tolist(), sizes.tolist()


def find_runs():
    runs = {}
    for suite in RESULTS.iterdir():
        config = suite / "config.json"
        if not config.exists():
            continue
        experiments = json.loads(config.read_text(encoding="utf-8"))["experiments"]
        if len(experiments) != 1 or experiments[0]["protocol"] not in ARMS:
            continue
        arm, k = experiments[0]["protocol"], experiments[0]["k"]
        for dataset in DATASETS:
            for seed in SEEDS:
                for model in MODELS:
                    run = suite / dataset / f"{arm}-k{k}" / f"seed-{seed}" / model
                    if (run / "result.json").exists():
                        runs[(dataset, k, arm, seed, model)] = run
    return runs


def stat(values):
    values = np.array(values, dtype=float)
    return values.mean(), values.std(ddof=1)


def main():
    runs = find_runs()
    total = len(DATASETS) * len(KS) * len(ARMS) * len(SEEDS) * len(MODELS)
    print(f"Completed runs: {len(runs)}/{total}")
    if len(runs) < total:
        print("Analysis uses complete runs only; do not read partial output as final.")
    scores, positives = {}, defaultdict(dict)
    identity = defaultdict(set)
    for key, run in sorted(runs.items()):
        dataset, k, arm, seed, model = key
        scores[key], labels, sizes = score(run)
        manifest = json.loads((run.parent / "manifest.json").read_text(encoding="utf-8"))
        identity[(dataset, k, seed)].add((manifest["shared_eval_sha256"], hash(tuple(labels)), hash(tuple(sizes))))
        counts = defaultdict(int)
        for y, size in zip(labels, sizes):
            counts[size] += y
        positives[(dataset, k)][seed] = dict(counts)
    assert all(len(v) == 1 for v in identity.values()), "Arms do not share evaluation candidates"

    lines = ["# Stress-test results", "", f"Completed runs: {len(runs)}/{total}. Generated by `analysis/stress_test.py`.",
             "Rules are in `STRESS_TEST_PLAN.md`. Losses are seen arm minus unseen arm, so positive means performance was lost by never seeing large hyperedges.", ""]
    failures = []
    for dataset in DATASETS:
        for k in KS:
            by_seed = positives[(dataset, k)]
            if not by_seed:
                continue
            common = set.intersection(*[set(c) for c in by_seed.values()])
            eligible = sorted(s for s in common if all(c[s] >= MIN_POSITIVES for c in by_seed.values()))
            metrics = ["ap_all"] + [f"ap_{s}" for s in eligible]
            lines += [f"## {dataset}, k={k}", "", f"Eligible sizes (at least {MIN_POSITIVES} positives in every seed): {eligible}", "",
                      "### AP on unseen arm, and losses", "",
                      "| Model | Metric | Unseen AP | Targets loss (primary) | Seeds | All loss (secondary) | Seeds | Failure |", "|---|---|---|---|---|---|---|---|"]
            for model in MODELS:
                for metric in metrics:
                    def values(arm):
                        return [scores[(dataset, k, arm, s, model)][metric] for s in SEEDS
                                if (dataset, k, arm, s, model) in scores and metric in scores[(dataset, k, arm, s, model)]]
                    unseen, targets, full = values("matched_unseen"), values("matched_targets"), values("matched_all")
                    if not (len(unseen) == len(targets) == len(full) == len(SEEDS)):
                        continue
                    primary = np.array(targets) - np.array(unseen)
                    secondary = np.array(full) - np.array(unseen)
                    mean, sd = stat(primary)
                    failed = bool(mean >= MIN_LOSS and (primary > 0).all() and mean > sd)
                    if failed:
                        failures.append((dataset, k, model, metric, mean, sd))
                    mean2, sd2 = stat(secondary)
                    lines.append(f"| {model} | {metric} | {np.mean(unseen):.3f} | {mean:+.3f} +/- {sd:.3f} | {(primary > 0).sum()}/3 | "
                                 f"{mean2:+.3f} +/- {sd2:.3f} | {(secondary > 0).sum()}/3 | {'YES' if failed else 'no'} |")
            lines += ["", "### Fixed threshold (descriptive): F1 and FPR", "",
                      "| Model | Unseen F1 | Targets F1 | All F1 | Unseen FPR | Targets FPR | All FPR |", "|---|---|---|---|---|---|---|"]
            for model in MODELS:
                cells = []
                for metric in ("f1_all", "fpr_all"):
                    for arm in ARMS:
                        got = [scores[(dataset, k, arm, s, model)][metric] for s in SEEDS if (dataset, k, arm, s, model) in scores]
                        cells.append(f"{np.mean(got):.3f}" if len(got) == len(SEEDS) else "-")
                lines.append(f"| {model} | " + " | ".join(cells) + " |")
            lines.append("")

    lines += ["## Decision", ""]
    if failures:
        lines.append("Failure rule met:")
        lines += [f"- {d}, k={k}, {m}, {metric}: {mean:+.3f} +/- {sd:.3f}" for d, k, m, metric, mean, sd in failures]
    else:
        lines.append("Failure rule not met for any model, dataset, k or metric.")
    lines += ["", "### Mechanisms against AllSet on the unseen arm, where failure was shown", ""]
    helped = False
    for dataset, k, metric in sorted({(d, k, metric) for d, k, _, metric, _, _ in failures}):
        for mechanism in MECHANISMS:
            pairs = [(dataset, k, "matched_unseen", s, mechanism) for s in SEEDS]
            base = [(dataset, k, "matched_unseen", s, "allset") for s in SEEDS]
            if not all(p in scores for p in pairs + base):
                continue
            delta = np.array([scores[p][metric] - scores[b][metric] for p, b in zip(pairs, base)])
            mean, sd = stat(delta)
            passed = bool((delta > 0).all() and mean > sd)
            helped |= passed
            lines.append(f"- {dataset}, k={k}, {metric}, {mechanism}: {mean:+.3f} +/- {sd:.3f}, {(delta > 0).sum()}/3, {'helps' if passed else 'no'}")
    if not failures:
        lines.append("Not applicable: no failure was shown.")
    elif not helped:
        lines += ["", "No mechanism met the rule."]
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUTPUT}")


if __name__ == "__main__":
    main()
